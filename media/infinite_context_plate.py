"""Infinite-context monument: ASCII isometric + SVG plate from live numbers.

Every number is passed in by the caller (measured, never recalled):
managed tokens, span files, vector chunks, live window tokens.
Prints the ASCII block to stdout and writes the SVG plate beside it.

Usage:
    python media/infinite_context_plate.py --tokens 3394962 --spans 1146 \\
        --chunks 61276 --window 389999 --out media/infinite-context.svg
"""

from __future__ import annotations

import argparse
import xml.etree.ElementTree as ET
from pathlib import Path

W = 56


def _slab(title: str, value: str) -> list:
    inner = W - 2
    label = f"  {title} "
    dots = "." * max(3, inner - len(label) - len(value) - 2)
    content = f"{label}{dots} {value}".ljust(inner)
    return [
        " " + "_" * inner + " ",
        "/" + " " * inner + "/|",
        "|" + " " * inner + "|  |",
        f"|{content}|  |",
        "|" + "_" * inner + "| /",
    ]


def render_ascii(tokens: int, spans: int, chunks: int, window: int) -> str:
    t = f"{tokens:,}"
    lines = [
        f"{t} TOKENS MANAGED — NOTHING EVICTED IS LOST",
        "",
        *_slab("LIVE WINDOW (tip)", f"~{window:,} tok"),
        *_slab("SUNK SPANS (.dtd verbatim)", f"{spans:,} files"),
        *_slab("CHROMA VECTORS (dual-ONNX)", f"{chunks:,} chunks"),
        "",
        "evicted is never deleted: sink verbatim, index, retrieve.",
        "RTR-RE:Symbiose · Reality is the judge.",
    ]
    return "\n".join(lines) + "\n"


def render_svg(tokens: int, spans: int, chunks: int, window: int) -> str:
    import math

    c30 = math.cos(math.radians(30))
    s30 = math.sin(math.radians(30))

    def iso(x, y, z):
        return (400 + (x - y) * c30, 300 + (x + y) * s30 - z)

    def poly(points, fill, stroke="#1a1d24"):
        pts = " ".join(f"{a:.1f},{b:.1f}" for a, b in points)
        return f"<polygon points='{pts}' fill='{fill}' stroke='{stroke}'/>"

    def text(x, y, s, size=14, fill="#1a1d24", bold=False):
        w = " font-weight='bold'" if bold else ""
        return (
            f"<text x='{x}' y='{y}' font-size='{size}'"
            f" fill='{fill}' text-anchor='middle'{w}>{s}</text>"
        )

    parts = []
    layers = [
        ("CHROMA VECTORS", f"{chunks:,} chunks", 0, "#7d3c98"),
        ("SUNK SPANS (.dtd)", f"{spans:,} files", 60, "#2874a6"),
        ("LIVE WINDOW", f"~{window:,} tok", 120, "#1a7f37"),
    ]
    L, D, H = 220, 130, 44
    for name, val, z, color in layers:
        top = [
            iso(-L / 2, -D / 2, z + H),
            iso(L / 2, -D / 2, z + H),
            iso(L / 2, D / 2, z + H),
            iso(-L / 2, D / 2, z + H),
        ]
        left = [
            iso(-L / 2, D / 2, z + H),
            iso(L / 2, D / 2, z + H),
            iso(L / 2, D / 2, z),
            iso(-L / 2, D / 2, z),
        ]
        right = [
            iso(L / 2, -D / 2, z + H),
            iso(L / 2, D / 2, z + H),
            iso(L / 2, D / 2, z),
            iso(L / 2, -D / 2, z),
        ]
        parts.append(poly(left, "#2e3440"))
        parts.append(poly(right, "#3f4653"))
        parts.append(poly(top, color))
        cx, cy = iso(0, 0, z + H)
        parts.append(
            text(cx, cy + 5, f"{name} · {val}", size=13, fill="#ffffff", bold=True)
        )
    parts.append(text(400, 60, f"{tokens:,} TOKENS MANAGED", size=26, bold=True))
    parts.append(text(400, 84, "evicted is never deleted — RTR-RE:Symbiose", size=13))
    body = "\n".join(parts)
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- GENERATED by media/infinite_context_plate.py from measured numbers;"
        " re-measure, then re-run. -->\n"
        "<svg xmlns='http://www.w3.org/2000/svg' width='800' height='420'"
        " viewBox='0 0 800 420'>\n"
        "<rect width='800' height='420' fill='#ffffff'/>\n"
        f"{body}\n</svg>\n"
    )


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="infinite_context_plate")
    ap.add_argument("--tokens", type=int, required=True)
    ap.add_argument("--spans", type=int, required=True)
    ap.add_argument("--chunks", type=int, required=True)
    ap.add_argument("--window", type=int, required=True)
    ap.add_argument("--out", type=str, default="media/infinite-context.svg")
    args = ap.parse_args(argv)
    text = render_ascii(args.tokens, args.spans, args.chunks, args.window)
    print(text)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        render_svg(args.tokens, args.spans, args.chunks, args.window),
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
