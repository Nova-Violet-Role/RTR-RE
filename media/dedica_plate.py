"""Dedica: the no-cache cost proof monument (TODO-15).

Beside the infinite-context monument: a 700k-window model operates a
multi-million-token RTR-managed context at lesser per-turn cost, with
no prompt cache and no RAG — because evicted substance lives in
retrieval form. Every number is passed in by the caller (measured).

Usage:
    python media/dedica_plate.py --managed 3430000 --live 390000 \\
        --retrieved 1000 --window 700000 --out media/dedica.svg
"""

from __future__ import annotations

import argparse
import xml.etree.ElementTree as ET
from pathlib import Path


def render_ascii(managed: int, live: int, retrieved: int, window: int) -> str:
    without = managed
    with_rtr = live + retrieved
    saved_pct = (1.0 - with_rtr / managed) * 100.0 if managed else 0.0
    lines = [
        "DEDICA — THE SMALL WINDOW THAT HOLDS THE LARGE WORLD",
        "",
        f"managed context .......... {managed:>12,} tok",
        f"served live tail ......... {live:>12,} tok",
        f"retrieved per turn ....... {retrieved:>12,} tok",
        f"model window ............. {window:>12,} tok",
        "",
        f"cost without RTR ......... {without:>12,} tok/turn",
        f"cost with RTR ............ {with_rtr:>12,} tok/turn",
        f"saved .................... {saved_pct:>11.1f} %",
        "",
        "no prompt cache. no RAG. the window lives in retrieval form.",
        "RTR-RE:Symbiose · Reality is the judge.",
    ]
    return "\n".join(lines) + "\n"


def render_svg(managed: int, live: int, retrieved: int, window: int) -> str:
    with_rtr = live + retrieved
    saved_pct = (1.0 - with_rtr / managed) * 100.0 if managed else 0.0
    left_w = 560
    right_w = max(8, int(560 * with_rtr / managed)) if managed else 8

    def bar(x, y, w, fill, label):
        return (
            f"<rect x='{x}' y='{y}' width='{w}' height='34' fill='{fill}'/>"
            f"<text x='{x + 8}' y='{y + 23}' font-size='13'"
            f" fill='#ffffff' font-weight='bold'>{label}</text>"
        )

    parts = [
        "<text x='400' y='52' font-size='24' fill='#1a1d24' text-anchor='middle'"
        " font-weight='bold'>DEDICA — cost without cache</text>",
        "<text x='400' y='74' font-size='13' fill='#1a1d24' text-anchor='middle'>"
        f"{managed:,} managed · {live:,} live + {retrieved:,} retrieved ·"
        f" {window:,} window</text>",
        bar(120, 110, left_w, "#b26a00", f"without RTR: {managed:,} tok/turn"),
        bar(120, 160, right_w, "#1a7f37", f"with RTR: {with_rtr:,} tok/turn"),
        "<text x='400' y='232' font-size='15' fill='#1a1d24' text-anchor='middle'>"
        f"saved {saved_pct:.1f}% — no prompt cache, no RAG</text>",
        "<text x='400' y='254' font-size='12' fill='#5b6472' text-anchor='middle'>"
        "evicted is never deleted — RTR-RE:Symbiose</text>",
    ]
    body = "\n".join(parts)
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- GENERATED by media/dedica_plate.py from measured numbers;"
        " re-measure, then re-run. -->\n"
        "<svg xmlns='http://www.w3.org/2000/svg' width='800' height='280'"
        " viewBox='0 0 800 280'>\n"
        "<rect width='800' height='280' fill='#ffffff'/>\n"
        f"{body}\n</svg>\n"
    )


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="dedica_plate")
    ap.add_argument("--managed", type=int, required=True)
    ap.add_argument("--live", type=int, required=True)
    ap.add_argument("--retrieved", type=int, required=True)
    ap.add_argument("--window", type=int, required=True)
    ap.add_argument("--out", type=str, default="media/dedica.svg")
    args = ap.parse_args(argv)
    print(render_ascii(args.managed, args.live, args.retrieved, args.window))
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        render_svg(args.managed, args.live, args.retrieved, args.window),
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
