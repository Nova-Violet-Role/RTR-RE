"""Plates for the preset-perf bench — data-driven SVG in the house style.

Reads eval/results/preset-perf.json, writes eval/preset-perf.svg +
eval/preset-perf-dark.svg. Edit the DATA (re-run the bench), then run
this script. Never hand-edit the SVG.

Usage:  python eval/plates_preset_perf.py
"""

import json
from pathlib import Path

HERE = Path(__file__).parent
RESULTS = HERE / "results" / "preset-perf.json"
FONT = "-apple-system,BlinkMacSystemFont,Segoe UI,Roboto,Helvetica,Arial,sans-serif"
MONO = "ui-monospace,SFMono-Regular,Menlo,Consolas,monospace"
W = 640


def esc(s):
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def render(data, dark):
    bg = "#1a1d24" if dark else "#ffffff"
    ink = "#e2e5ec" if dark else "#1a1d24"
    muted = "#9aa3b2" if dark else "#5b6472"
    grid = "#2e3440" if dark else "#e2e5ec"
    hero = "#bb86fc" if dark else "#7d3c98"
    combos = data["combos"]
    parts = []
    y = 44

    def text(x, yy, s, size=13, fill=None, mono=False, bold=False):
        f = MONO if mono else FONT
        w = " font-weight='bold'" if bold else ""
        parts.append(
            f"<text x='{x}' y='{yy}' font-family='{f}' font-size='{size}'"
            f" fill='{fill or ink}'{w}>{esc(s)}</text>"
        )

    text(24, y, "CPU preset performance (12 files, 10 queries)", size=19, bold=True)
    y += 22
    text(
        24,
        y,
        "single-model bge-base · isolated DB per combo",
        size=12,
        fill=muted,
        mono=True,
    )
    y += 16
    scale = 280.0 / max(c["index_s"] for c in combos)
    for c in combos:
        y += 26
        text(24, y, f"T{c['threads']}", size=13, mono=True, bold=True)
        bw = max(2, c["index_s"] * scale)
        parts.append(
            f"<rect x='80' y='{y - 13}' width='{bw:.1f}' height='15' fill='{hero}'/>"
        )
        text(
            90 + bw,
            y,
            f"index {c['index_s']}s · p50 {c['search_p50_ms']}ms",
            size=11,
            fill=muted,
            mono=True,
        )
    y += 34
    text(
        24,
        y,
        "generated by eval/plates_preset_perf.py · Nova-Violet Role",
        size=11,
        fill=muted,
    )
    height = y + 24
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- GENERATED by eval/plates_preset_perf.py; re-run the bench, then this script. -->\n"
        f"<svg xmlns='http://www.w3.org/2000/svg' width='{W}' height='{height}'"
        f" viewBox='0 0 {W} {height}' font-family='{FONT}'>\n"
        f"<rect width='{W}' height='{height}' fill='{bg}'/>\n"
        + "\n".join(parts)
        + "\n</svg>\n"
    )


def main():
    data = json.loads(RESULTS.read_text(encoding="utf-8"))
    (HERE / "preset-perf.svg").write_text(
        render(data, dark=False), encoding="utf-8", newline="\n"
    )
    (HERE / "preset-perf-dark.svg").write_text(
        render(data, dark=True), encoding="utf-8", newline="\n"
    )
    print("wrote eval/preset-perf.svg + eval/preset-perf-dark.svg")


if __name__ == "__main__":
    main()
